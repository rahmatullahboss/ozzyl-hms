import { sql } from 'drizzle-orm';
import { check, index, integer, sqliteTable, text, uniqueIndex } from 'drizzle-orm/sqlite-core';

const utcNow = sql`(strftime('%Y-%m-%dT%H:%M:%fZ','now'))`;
const sha256Check = (column: ReturnType<typeof text>) => sql`
  length(${column}) = 64
  AND ${column} = lower(${column})
  AND ${column} NOT GLOB '*[^0-9a-f]*'
`;

export const canonicalLabSpecimens = sqliteTable(
  'canonical_lab_specimens',
  {
    id: integer('id').primaryKey({ autoIncrement: true }),
    tenantId: text('tenant_id').notNull(),
    specimenPublicId: text('specimen_public_id').notNull(),
    patientLinkPublicId: text('patient_link_public_id').notNull(),
    encounterPublicId: text('encounter_public_id').notNull(),
    primaryRequestPublicId: text('primary_request_public_id').notNull(),
    primaryServicePublicId: text('primary_service_public_id').notNull(),
    accessionNamespace: text('accession_namespace').notNull(),
    accessionValue: text('accession_value').notNull(),
    barcodeNamespace: text('barcode_namespace').notNull(),
    barcodeValue: text('barcode_value').notNull(),
    specimenTypeCode: text('specimen_type_code').notNull(),
    containerCode: text('container_code'),
    parentSpecimenPublicId: text('parent_specimen_public_id'),
    currentStatus: text('current_status').notNull().default('registered'),
    statusVersion: integer('status_version').notNull().default(1),
    currentStatusEventPublicId: text('current_status_event_public_id'),
    collectedAtUtc: text('collected_at_utc'),
    receivedAtUtc: text('received_at_utc'),
    rejectedAtUtc: text('rejected_at_utc'),
    disposedAtUtc: text('disposed_at_utc'),
    actorUserPublicId: text('actor_user_public_id'),
    actorSystemKey: text('actor_system_key'),
    idempotencyKey: text('idempotency_key').notNull(),
    requestFingerprintSha256: text('request_fingerprint_sha256').notNull(),
    sourceEvidenceSha256: text('source_evidence_sha256').notNull(),
    createdAtUtc: text('created_at_utc').notNull().default(utcNow),
    updatedAtUtc: text('updated_at_utc').notNull().default(utcNow),
  },
  (table) => [
    uniqueIndex('uq_canonical_lab_specimens_public_id').on(table.tenantId, table.specimenPublicId),
    uniqueIndex('uq_canonical_lab_specimens_patient_scope').on(
      table.tenantId,
      table.specimenPublicId,
      table.patientLinkPublicId,
      table.encounterPublicId,
    ),
    uniqueIndex('uq_canonical_lab_specimens_request_scope').on(
      table.tenantId,
      table.specimenPublicId,
      table.primaryRequestPublicId,
      table.primaryServicePublicId,
    ),
    uniqueIndex('uq_canonical_lab_specimens_accession').on(
      table.tenantId,
      table.accessionNamespace,
      table.accessionValue,
    ),
    uniqueIndex('uq_canonical_lab_specimens_barcode').on(
      table.tenantId,
      table.barcodeNamespace,
      table.barcodeValue,
    ),
    uniqueIndex('uq_canonical_lab_specimens_idempotency').on(table.tenantId, table.idempotencyKey),
    index('idx_canonical_lab_specimens_patient_status').on(
      table.tenantId,
      table.patientLinkPublicId,
      table.currentStatus,
      table.specimenPublicId,
    ),
    index('idx_canonical_lab_specimens_request').on(
      table.tenantId,
      table.primaryRequestPublicId,
      table.currentStatus,
      table.specimenPublicId,
    ),
    check(
      'canonical_lab_specimens_status_check',
      sql`${table.currentStatus} IN ('registered','collected','in_transit','received','processing','rejected','disposed','entered_in_error')`,
    ),
    check('canonical_lab_specimens_status_version_check', sql`${table.statusVersion} > 0`),
    check(
      'canonical_lab_specimens_actor_check',
      sql`${table.actorUserPublicId} IS NOT NULL OR ${table.actorSystemKey} IS NOT NULL`,
    ),
    check('canonical_lab_specimens_fingerprint_check', sha256Check(table.requestFingerprintSha256)),
    check('canonical_lab_specimens_evidence_check', sha256Check(table.sourceEvidenceSha256)),
  ],
);

